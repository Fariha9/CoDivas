import jsPDF from "jspdf";

const generateCertificate = (studentName, courseName, certData) => {
  const doc = new jsPDF("landscape", "pt", "a4");

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  
  // Background
  
  doc.setFillColor(255, 255, 255);
  doc.rect(0, 0, pageWidth, pageHeight, "F");

  
  // Outer Border
  
  doc.setDrawColor(76, 29, 149);
  doc.setLineWidth(18);
  doc.rect(25, 25, pageWidth - 50, pageHeight - 50);

  // Inner Border
  doc.setDrawColor(190, 170, 240);
  doc.setLineWidth(2);
  doc.rect(45, 45, pageWidth - 90, pageHeight - 90);

  
  // Certificate Number
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(120);

  doc.text(
    `Certificate No : ${certData.certificateID}`,
    pageWidth - 240,
    70
  );

 
  // Branding
 
  doc.setFont("helvetica", "bold");
  doc.setFontSize(32);
  doc.setTextColor(76, 29, 149);

  doc.text("CoDivas", pageWidth / 2, 85, {
    align: "center",
  });

  doc.setFont("helvetica", "italic");
  doc.setFontSize(14);
  doc.setTextColor(120);

  doc.text(
    "Empowering Future Developers",
    pageWidth / 2,
    108,
    { align: "center" }
  );

  
  
  // Title

  doc.setFont("helvetica", "bold");
  doc.setFontSize(34);
  doc.setTextColor(0);

  doc.text(
    "CERTIFICATE OF COMPLETION",
    pageWidth / 2,
    155,
    {
      align: "center",
    }
  );


  // Intro
  
  doc.setFont("times", "normal");
  doc.setFontSize(18);
  doc.setTextColor(90);

  doc.text(
    "This certificate is proudly presented to",
    pageWidth / 2,
    205,
    {
      align: "center",
    }
  );

  
  // Student Name
 
  doc.setFont("times", "bold");
  doc.setFontSize(42);
  doc.setTextColor(76, 29, 149);

  doc.text(studentName, pageWidth / 2, 265, {
    align: "center",
  });

  // Decorative Line
  doc.setDrawColor(212, 175, 55);
  doc.setLineWidth(1.2);
  doc.line(pageWidth / 2 - 120, 278, pageWidth / 2 + 120, 278);

 
  // Course

  doc.setFont("times", "normal");
  doc.setFontSize(18);
  doc.setTextColor(90);

  doc.text(
    "for successfully completing the course",
    pageWidth / 2,
    315,
    {
      align: "center",
    }
  );

  doc.setFont("helvetica", "bold");
  doc.setFontSize(27);
  doc.setTextColor(0);

  doc.text(
    courseName.toUpperCase(),
    pageWidth / 2,
    360,
    {
      align: "center",
    }
  );


  // Description
  
  doc.setFont("helvetica", "italic");
  doc.setFontSize(13);
  doc.setTextColor(110);

  const desc =
    "This certificate is awarded in recognition of successfully completing all learning activities and demonstrating dedication, commitment, and excellence throughout the course.";

  doc.text(
    doc.splitTextToSize(desc, 500),
    pageWidth / 2,
    405,
    {
      align: "center",
    }
  );


  // Gold Seal
  
  doc.setFillColor(255, 248, 220);
  doc.setDrawColor(212, 175, 55);

  doc.circle(130, 210, 42, "FD");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(180, 140, 20);

  doc.text("CERTIFIED", 130, 206, {
    align: "center",
  });

  doc.text("2026", 130, 220, {
    align: "center",
  });

  
  // Issue Date
  
  const issueDate = new Date().toLocaleDateString("en-GB", {
    day: "2-digit",
    month: "long",
    year: "numeric",
  });

 
  // Footer Information
  
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(0);

  doc.text(
    `Certificate ID : ${certData.certificateID}`,
    90,
    470
  );

  doc.text(
    `Grade : ${certData.grade || "A+"}`,
    90,
    490
  );

  doc.text(
    `Instructor : ${
      certData.instructorName || "CoDivas Instructor"
    }`,
    90,
    510
  );

  doc.text(
    `Issue Date : ${issueDate}`,
    90,
    530
  );

 
  // Signature
  
  doc.setFont("times", "italic");
  doc.setFontSize(24);
  doc.setTextColor(76, 29, 149);

  doc.text(
    "Dr. Sarah Ahmed",
    pageWidth - 175,
    480,
    {
      align: "center",
    }
  );

  doc.setDrawColor(76, 29, 149);

  doc.line(
    pageWidth - 280,
    495,
    pageWidth - 70,
    495
  );

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.setTextColor(0);

  doc.text(
    "Authorized Signature",
    pageWidth - 175,
    515,
    {
      align: "center",
    }
  );

  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  doc.text(
    "Director, CoDivas Learning",
    pageWidth - 175,
    530,
    {
      align: "center",
    }
  );


  // Footer
  
  doc.setFont("helvetica", "italic");
  doc.setFontSize(10);
  doc.setTextColor(120);

  doc.text(
    "Generated by CoDivas E-Learning Platform",
    pageWidth / 2,
    pageHeight - 35,
    {
      align: "center",
    }
  );

  
  // Save
  
  doc.save(
    `${studentName.replace(/\s+/g, "_")}_Certificate.pdf`
  );
};

export default generateCertificate;